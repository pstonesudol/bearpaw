import { API_BASE } from './useApi';
import type {
  AudioDevicesResponse,
  HitDetail,
  HitPage,
  HitWaveform,
  RecordingStatusSnapshot,
  RecordingsSummary,
} from '../types';

/**
 * REST calls for recordings, transcripts and searchable history.
 *
 * Kept out of `ScannerAPIClient` because that class is the scanner command
 * surface; these are media and history reads, and a failure here must never be
 * mistaken for a scanner failure.
 */

async function request<T>(path: string, init?: RequestInit): Promise<T> {
  const response = await fetch(`${API_BASE}${path}`, {
    ...init,
    headers: {
      'Content-Type': 'application/json',
      ...init?.headers,
    },
  });
  if (!response.ok) {
    let message = response.statusText;
    try {
      const payload = (await response.json()) as { error?: string; message?: string };
      message = payload.error ?? payload.message ?? message;
    } catch {
      // A non-JSON error body is still an error; the status text stands in.
    }
    throw new Error(`${message} (${response.status})`);
  }
  if (response.status === 204) return undefined as T;
  return (await response.json()) as T;
}

export interface HitQuery {
  search?: string;
  channel?: number;
  frequency?: number;
  start_time?: number;
  end_time?: number;
  has_recording?: boolean;
  recording_status?: string;
  transcript_status?: string;
  sort?: 'timestamp' | 'frequency' | 'duration' | 'channel';
  order?: 'asc' | 'desc';
  limit?: number;
  offset?: number;
}

export function getHits(query: HitQuery = {}): Promise<HitPage> {
  const params = new URLSearchParams();
  for (const [key, value] of Object.entries(query)) {
    if (value === undefined || value === null || value === '') continue;
    params.set(key, String(value));
  }
  const suffix = params.toString();
  return request<HitPage>(`/hits${suffix ? `?${suffix}` : ''}`);
}

export function getHit(id: string): Promise<HitDetail> {
  return request<HitDetail>(`/hits/${encodeURIComponent(id)}`);
}

export function editTranscript(id: string, transcript: string): Promise<HitDetail> {
  return request<HitDetail>(`/hits/${encodeURIComponent(id)}/transcript`, {
    method: 'PATCH',
    body: JSON.stringify({ transcript }),
  });
}

export function transcribeHit(id: string, force = false): Promise<{ transcript_status: string }> {
  return request(`/hits/${encodeURIComponent(id)}/transcribe`, {
    method: 'POST',
    body: JSON.stringify({ force }),
  });
}

export function deleteRecording(
  id: string,
): Promise<{ hit_uid: string; deleted_audio: boolean; transcript_cleared: boolean }> {
  return request(`/hits/${encodeURIComponent(id)}/recording`, { method: 'DELETE' });
}

export function getAudioDevices(): Promise<AudioDevicesResponse> {
  return request<AudioDevicesResponse>('/audio/devices');
}

export function getAudioStatus(): Promise<RecordingStatusSnapshot> {
  return request<RecordingStatusSnapshot>('/audio/status');
}

/**
 * Library totals for the history header.
 *
 * Deliberately not part of `/audio/status`: the settings sheet polls that one
 * for the level meter, and this is a database aggregate rather than a snapshot
 * of live capture.
 */
export function getRecordingsSummary(): Promise<RecordingsSummary> {
  return request<RecordingsSummary>('/recordings/summary');
}

export function testAudioRecording(seconds = 3): Promise<{ file: string; duration_secs: number }> {
  return request('/audio/test', {
    method: 'POST',
    body: JSON.stringify({ seconds }),
  });
}

/**
 * Peak shape of a recording, for the row's waveform.
 *
 * Decoded server-side so the list can draw a row without downloading its audio.
 */
export function getHitWaveform(id: string, buckets = 64): Promise<HitWaveform> {
  return request<HitWaveform>(`/hits/${encodeURIComponent(id)}/waveform?buckets=${buckets}`);
}

/**
 * The `<audio>` source for a hit.
 *
 * The id is encoded: hit uids are generated by the backend and are URL-safe
 * today, but a numeric fallback id from a pre-recording row must not be able to
 * break the path either.
 */
export function hitAudioUrl(id: string): string {
  return `${API_BASE}/hits/${encodeURIComponent(id)}/audio`;
}
